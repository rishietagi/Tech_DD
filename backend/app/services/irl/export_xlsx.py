"""Excel export of the IRL — the artefact that actually goes to the target.

Five columns since 2026-09-02: **Scope Area | Function | Type | Request | Response**.

`Type` is Document or Question. An IRL asks for both — an artefact the target hands over,
and an explanation only management can give — and the client needs to know which is which
before they start: one goes to whoever pulls files, the other to whoever can answer it.

`Scope Area` is the scope-of-work heading the request traces to, so the workbook groups by
the same areas the deck opened. `Function` is who owns the answer, which is what makes the
sheet routable — a function's owner can filter to their own rows. Response is the column
the client fills in and sends back.

A hidden fifth column carries the question id. It is what
`services/irl/import_xlsx.py` matches on when the completed workbook is uploaded, so
responses land against the right request even if rows have been reordered or reworded.

Any responses already typed in the app are written into the Response column, so the
workbook round-trips rather than discarding work.

`xlsxwriter` is already in the environment (python-pptx depends on it) and is pinned
explicitly in requirements.txt.
"""

import io
import re
from dataclasses import dataclass
from typing import Any

import xlsxwriter

from app.models.estate import InventoryItem
from app.schemas.estate import ProcessRef
from app.schemas.irl import IrlPayload
from app.services.estate.inventory_xlsx import write_inventory_sheets

SHEET_NAME = "Initial Request List"

# Wide enough to read without resizing, narrow enough to print. Response gets the most
# room because that is where the target writes.
_COL_SCOPE_AREA = 28
_COL_FUNCTION = 20
_COL_TYPE = 11
_COL_QUESTION = 70
_COL_RESPONSE = 56

# The question id travels with the workbook so an upload can match rows back exactly.
# Hidden rather than removed: matching on text alone breaks the moment anyone edits a
# question, and a visible id column is noise to the client.
ID_HEADER = "Request ID"

_ROW_HEIGHT = 34


def render_xlsx(
    payload: IrlPayload,
    responses: dict[str, str] | None = None,
    inventory: "InventorySheets | None" = None,
) -> bytes:
    """The IRL as a .xlsx workbook, returned as bytes.

    With `inventory`, the workbook also carries the Application Inventory, Data Domains
    and Technology Platforms sheets (PHASE6_PLAN D2), pre-filled with whatever is already
    recorded, so the target completes one file and returns one file.
    """
    answers = responses or {}
    buf = io.BytesIO()

    workbook = xlsxwriter.Workbook(buf, {"in_memory": True, "constant_memory": False})
    workbook.set_properties(
        {
            "title": f"Initial Request List — {payload.company_name or 'Target'}",
            "subject": "Technology due diligence",
            "comments": "Generated by the KPMG Tech Diligence Tool.",
        }
    )

    header = workbook.add_format(
        {
            "bold": True,
            "font_color": "#FFFFFF",
            "bg_color": "#00338D",
            "align": "left",
            "valign": "vcenter",
            "border": 1,
            "border_color": "#DDE3ED",
        }
    )
    cell = workbook.add_format(
        {"valign": "top", "text_wrap": True, "border": 1, "border_color": "#DDE3ED"}
    )
    function_cell = workbook.add_format(
        {
            "valign": "top",
            "text_wrap": True,
            "bold": True,
            "border": 1,
            "border_color": "#DDE3ED",
        }
    )
    # Unlocked and tinted so it reads as "your turn" when the target opens the file.
    response_cell = workbook.add_format(
        {
            "valign": "top",
            "text_wrap": True,
            "border": 1,
            "border_color": "#DDE3ED",
            "bg_color": "#F4F6FA",
        }
    )

    sheet = workbook.add_worksheet(SHEET_NAME)
    sheet.set_column(0, 0, _COL_SCOPE_AREA)
    sheet.set_column(1, 1, _COL_FUNCTION)
    sheet.set_column(2, 2, _COL_TYPE)
    sheet.set_column(3, 3, _COL_QUESTION)
    sheet.set_column(4, 4, _COL_RESPONSE)
    sheet.set_column(5, 5, 18, None, {"hidden": True})

    sheet.write(0, 0, "Scope Area", header)
    sheet.write(0, 1, "Function", header)
    sheet.write(0, 2, "Type", header)
    sheet.write(0, 3, "Request", header)
    sheet.write(0, 4, "Response", header)
    sheet.write(0, 5, ID_HEADER, header)

    # Header stays visible while the target scrolls a long list, and the filter lets
    # each function's owner see only their own rows.
    sheet.freeze_panes(1, 0)

    # Grouped by function so the workbook matches the on-screen order, and so one
    # function's rows sit together for whoever it is forwarded to.
    ordered = _ordered_questions(payload)

    for index, question in enumerate(ordered, start=1):
        sheet.set_row(index, _ROW_HEIGHT)
        sheet.write(index, 0, question.scope_area or "Additional requests", function_cell)
        sheet.write(index, 1, question.function, cell)
        # Title case for the client: "Document" reads as an instruction, "document" as a
        # database value.
        sheet.write(index, 2, "Question" if question.kind == "question" else "Document", cell)
        sheet.write(index, 3, question.question, cell)
        sheet.write(index, 4, answers.get(question.id, ""), response_cell)
        sheet.write(index, 5, question.id, cell)

    last_row = max(1, len(ordered))
    sheet.autofilter(0, 0, last_row, 5)

    if inventory is not None:
        write_inventory_sheets(workbook, inventory.items, inventory.processes)
    # The request list stays the sheet the workbook opens on.
    sheet.activate()

    workbook.close()
    return buf.getvalue()


def _ordered_questions(payload: IrlPayload) -> list[Any]:
    """Questions in function order, falling back to payload order.

    `functions` carries the resolved grouping; if it is somehow absent or incomplete,
    every question must still be exported — losing a request silently would be worse
    than an imperfect order.
    """
    by_id = {q.id: q for q in payload.questions}
    ordered: list[Any] = []
    seen: set[str] = set()

    for function in payload.functions:
        for question_id in function.question_ids:
            question = by_id.get(question_id)
            if question is not None and question_id not in seen:
                ordered.append(question)
                seen.add(question_id)

    for question in payload.questions:
        if question.id not in seen:
            ordered.append(question)
            seen.add(question.id)

    return ordered


@dataclass
class InventorySheets:
    """What the IRL workbook needs to write the inventory sheets."""

    items: list[InventoryItem]
    processes: list[ProcessRef]


def render_xlsx_from_payload(
    payload: dict[str, Any],
    responses: dict[str, str] | None = None,
    inventory: InventorySheets | None = None,
) -> bytes:
    """Render a stored payload. Only schema v1 exists so far."""
    if payload.get("schema_version") != 1:
        raise ValueError("Only schema v1 request lists can be exported to Excel")
    return render_xlsx(IrlPayload.model_validate(payload), responses, inventory)


def xlsx_filename(deal_name: str, version: int) -> str:
    """`project-redline-irl-v2.xlsx`, matching the PDF and PPT naming."""
    slug = re.sub(r"[^a-z0-9]+", "-", deal_name.lower()).strip("-")
    return f"{slug}-irl-v{version}.xlsx" if slug else f"irl-v{version}.xlsx"
